import { z } from "zod";

import type { EntityKey } from "@/lib/entities/config";

/**
 * Field rules for the create / edit forms — mirrored from the live schema
 * (CHECK constraints, unique indexes and BEFORE triggers), verified per table:
 *
 * | table       | name (after btrim) | unique name       | description        | department_id |
 * |-------------|--------------------|-------------------|--------------------|---------------|
 * | departments | 2–32               | lower(btrim(name)) | NULL or 2–512      | —             |
 * | brands      | 2–32               | lower(name)       | NULL or 2–256      | —             |
 * | categories  | 2–64               | none              | NULL or 2–256 (*)  | NULL or FK    |
 * | collections | 2–32               | lower(name)       | NULL, no limit     | —             |
 *
 * (*) categories only trims description; an empty string would violate the
 *     CHECK, so empty input is always sent as NULL.
 *
 * `slug` is generated by triggers from the name (department_slugify), and the
 * generator rejects names with fewer than 2 letters/digits — validated here so
 * users see it before submitting. `display_order`, ids, audit and timestamp
 * columns are database-owned and never accepted from the client.
 */

export type EntityFormRules = {
  nameMax: number;
  /** Case-insensitive unique index on the name. */
  uniqueName: boolean;
  /** `null` = no CHECK constraint on length. */
  descriptionMax: number | null;
  /** Slug is generated from the name by a trigger. */
  hasSlug: boolean;
  hasDepartment: boolean;
  /** Supabase Storage bucket validated by `enforce_image_reference`. */
  bucket: `${EntityKey}-images`;
};

export const ENTITY_FORM_RULES: Record<EntityKey, EntityFormRules> = {
  departments: { nameMax: 32, uniqueName: true, descriptionMax: 512, hasSlug: true, hasDepartment: false, bucket: "departments-images" },
  brands: { nameMax: 32, uniqueName: true, descriptionMax: 256, hasSlug: true, hasDepartment: false, bucket: "brands-images" },
  categories: { nameMax: 64, uniqueName: false, descriptionMax: 256, hasSlug: false, hasDepartment: true, bucket: "categories-images" },
  collections: { nameMax: 32, uniqueName: true, descriptionMax: null, hasSlug: true, hasDepartment: false, bucket: "collections-images" },
};

/** Bucket limits (storage.buckets): 1 MiB, png / webp / jpeg. */
export const IMAGE_MAX_BYTES = 1_048_576;
export const IMAGE_MIME_TYPES = ["image/png", "image/webp", "image/jpeg", "image/jpg"] as const;

/** Object keys we generate: `<uuid>.<ext>` — also satisfies validate_image_reference. */
export const STORAGE_PATH_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(webp|png|jpe?g)$/;

/** JS port of `public.department_slugify` (used by every slug trigger). */
export function slugify(input: string): string {
  const slug = input
    .trim()
    .toLowerCase()
    .replace(/['"]+/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug;
}

/** Preview of the generated base slug (the DB may append `-2`, `-3`… on collision). */
export function previewSlug(name: string, maxLength = 32): string {
  return slugify(name).slice(0, maxLength).replace(/^-+|-+$/g, "");
}

/* ------------------------------------------------------------- fields */

function nameSchema(rules: EntityFormRules) {
  let schema = z
    .string({ error: "Enter a name." })
    .trim()
    .min(1, "Enter a name.")
    .min(2, "Use at least 2 characters.")
    .max(rules.nameMax, `Use ${rules.nameMax} characters or fewer.`);
  if (rules.hasSlug) {
    schema = schema.refine((value) => previewSlug(value).length >= 2, {
      message: "Include at least 2 letters or numbers (used for the web address).",
    });
  }
  return schema;
}

function descriptionSchema(rules: EntityFormRules) {
  return z
    .string()
    .trim()
    .refine((value) => value === "" || value.length >= 2, "Use at least 2 characters, or leave it empty.")
    .refine(
      (value) => rules.descriptionMax === null || value.length <= rules.descriptionMax,
      rules.descriptionMax === null ? "" : `Use ${rules.descriptionMax} characters or fewer.`,
    );
}

/* --------------------------------------------------------- form values */

export type ImageValue =
  | { kind: "none" }
  | { kind: "existing"; url: string }
  | { kind: "new"; file: File; previewUrl: string };

export type EntityFormValues = {
  name: string;
  description: string;
  isActive: boolean;
  /** "" = no department (categories only). */
  departmentId: string;
  image: ImageValue;
};

/** Client-side form schema (React Hook Form). */
export function formSchemaFor(entity: EntityKey) {
  const rules = ENTITY_FORM_RULES[entity];
  return z.object({
    name: nameSchema(rules),
    description: descriptionSchema(rules),
    isActive: z.boolean(),
    departmentId: rules.hasDepartment ? z.union([z.literal(""), z.uuid("Choose a valid department.")]) : z.literal(""),
    image: z.custom<ImageValue>(),
  });
}

/* ------------------------------------------------------- wire payload */

const imageActionSchema = z.discriminatedUnion("action", [
  z.object({ action: z.literal("keep") }),
  z.object({ action: z.literal("remove") }),
  z.object({ action: z.literal("set"), path: z.string().regex(STORAGE_PATH_PATTERN, "Invalid image reference.") }),
]);

export type ImageAction = z.infer<typeof imageActionSchema>;

/**
 * JSON body for POST/PATCH. Re-validated on the server with the same rules;
 * description is normalised to NULL when empty.
 */
export function payloadSchemaFor(entity: EntityKey, mode: "create" | "update") {
  const rules = ENTITY_FORM_RULES[entity];
  const base = z.object({
    name: nameSchema(rules),
    description: descriptionSchema(rules).transform((value) => (value === "" ? null : value)),
    isActive: z.boolean(),
    departmentId: rules.hasDepartment ? z.uuid().nullable() : z.null().optional(),
    image: imageActionSchema,
  });
  if (mode === "create") {
    // Client-generated id lets an uncertain create be verified without a unique
    // name (categories). Departments ignore it: a trigger always assigns the id.
    return base.extend({ clientId: z.uuid().optional() });
  }
  return base.extend({
    /** Optimistic concurrency token from the loaded record. */
    expectedUpdatedAt: z.string().min(10).max(64),
    /** Overwrite even if the record changed since it was loaded. */
    force: z.boolean().optional(),
  });
}

/** JSON sent by the form (validated on the server by `payloadSchemaFor`). */
export type EntityPayloadInput = {
  name: string;
  description: string;
  isActive: boolean;
  departmentId?: string | null;
  image: ImageAction;
  clientId?: string;
  expectedUpdatedAt?: string;
  force?: boolean;
};

/** Editable record as returned by GET /api/entities/:entity/:id. */
export type EntityRecord = {
  id: string;
  name: string;
  slug: string | null;
  description: string | null;
  isActive: boolean;
  departmentId: string | null;
  imageUrl: string | null;
  storagePath: string | null;
  updatedAt: string;
};

/** Field keys a server error can be attached to. */
export type EntityFormField = "name" | "description" | "departmentId" | "image";

export type FieldErrors = Partial<Record<EntityFormField, string>>;

/** Turns Zod issues into `{ field: firstMessage }`. */
export function toFieldErrors(error: z.ZodError): FieldErrors {
  const result: FieldErrors = {};
  for (const issue of error.issues) {
    const key = issue.path[0];
    if ((key === "name" || key === "description" || key === "departmentId" || key === "image") && !result[key]) {
      result[key] = issue.message;
    }
  }
  return result;
}

/**
 * Products module constants — every limit here is mirrored from the live
 * Supabase schema (CHECK constraints, unique indexes, triggers). The database
 * stays authoritative; these only give early, field-level feedback.
 *
 * products
 *   name         text NOT NULL, btrim length 2–128           (products_name_length_check)
 *   description  NULL or btrim length 2–2048                 (products_description_length_check)
 *   price        numeric NOT NULL, 1–1,000,000               (products_price_range_check)
 *   discount     numeric NOT NULL DEFAULT 0, 0–99 (percent)  (products_discount_range_check)
 *   label        NULL or btrim length 2–16                   (products_label_length_check)
 *   label_color  NULL or ^#[0-9A-Fa-f]{6}$                   (products_label_color_format_check)
 *   label_bg     NULL or ^#[0-9A-Fa-f]{6}$                   (products_label_bg_format_check)
 *   brand_id / category_id / collection_id   NULL or FK, ON DELETE SET NULL
 *   display_order  UNIQUE, NULL = end of the list (managed by reorder_catalog_entity)
 *   cover image      → bucket cover-products-images  (enforce_image_reference)
 *   size-table image → bucket size-table-images      (enforce_image_reference)
 *   Department is not a product column: it comes from the category.
 *
 * variants
 *   size        btrim length 1–32, stored upper-cased       (variants_size_length_check + trigger)
 *   color_hash  ^#[0-9A-Fa-f]{6}$, stored upper-cased       (variants_color_hash_format_check + trigger)
 *   color_name  btrim length 2–32                           (variants_color_name_length_check)
 *   UNIQUE (product_id, size, color_hash)                   (variants_identity_key)
 *   stock       bigint NOT NULL DEFAULT 1 (no range CHECK — pre-orders can take it below 0)
 *   maximum_preorder_quantity  bigint >= 0                  (variants_maximum_preorder_quantity_check)
 *   barcode     10 digits, generated by the database — never sent by the client
 *   is_printed  only via mark_variant_as_printed(); once printed (or while in a
 *               cart) size / colour / barcode are locked and the variant can't be deleted.
 *   image       → bucket variants-images
 */


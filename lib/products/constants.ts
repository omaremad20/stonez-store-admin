export const PRODUCTS_HREF = "/products";

export const productRoutes = {
  list: PRODUCTS_HREF,
  create: `${PRODUCTS_HREF}/new`,
  detail: (id: string) => `${PRODUCTS_HREF}/${id}`,
  edit: (id: string) => `${PRODUCTS_HREF}/${id}/edit`,
};

/**
 * Validates a `?from=` return URL: only the products listing (with its query
 * state) is accepted, so the param can't redirect anywhere else.
 */
export function safeProductsListUrl(raw: string | string[] | undefined | null): string {
  if (typeof raw !== "string" || raw.length > 512) return PRODUCTS_HREF;
  try {
    const url = new URL(raw, "http://stonez.local");
    if (url.origin !== "http://stonez.local" || url.pathname !== PRODUCTS_HREF) return PRODUCTS_HREF;
    return `${url.pathname}${url.search}`;
  } catch {
    return PRODUCTS_HREF;
  }
}

const DETAIL_PATH = /^\/products\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Return URL for the create / edit forms: the products listing (with its
 * query) or a product details page (whose own `?from=` is preserved). Anything
 * else falls back to the listing.
 */
export function safeProductReturnUrl(raw: string | string[] | undefined | null): string {
  if (typeof raw !== "string" || raw.length > 1024) return PRODUCTS_HREF;
  try {
    const url = new URL(raw, "http://stonez.local");
    if (url.origin !== "http://stonez.local") return PRODUCTS_HREF;
    if (url.pathname === PRODUCTS_HREF) return `${url.pathname}${url.search}`;
    if (DETAIL_PATH.test(url.pathname)) {
      const from = safeProductsListUrl(url.searchParams.get("from"));
      return from === PRODUCTS_HREF ? url.pathname : `${url.pathname}?from=${encodeURIComponent(from)}`;
    }
    return PRODUCTS_HREF;
  } catch {
    return PRODUCTS_HREF;
  }
}

